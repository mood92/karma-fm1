"""Main Menu line logo -> firmware/src/mm_logo.h: a 20 x 20 picture, 4 bits a pixel (low nibble first, as op_sprites.h),
index 3 = white line, 2 = dim line. Source: assets/logo/mainmenu-line.png (black lines on white).
  tools/gen_mm_logo.py"""
from pathlib import Path
from PIL import Image, ImageFilter

N = 20
root = Path(__file__).resolve().parent.parent
im = Image.open(root / "assets/logo/mainmenu-line.png").convert("L")
bb = Image.eval(im, lambda v: 255 - v).getbbox()
im0 = im.crop(bb)
im = im0
s = max(im.size)
sq = Image.new("L", (s, s), 255)
sq.paste(im, ((s - im.width) // 2, (s - im.height) // 2))
sq = sq.filter(ImageFilter.MinFilter(15))          # thicken the lines: 1 px wide at this size
im = sq.resize((N, N), Image.BOX)
pix = []
for y in range(N):
    for x in range(N):
        ink = 255 - im.getpixel((x, y))
        pix.append(3 if ink > 90 else 2 if ink > 40 else 0)
data = []
for i in range(0, len(pix), 2):
    data.append(pix[i] | pix[i + 1] << 4)
body = ",".join(str(b) for b in data)
(root / "firmware/src/mm_logo.h").write_text(
    "/* generated by tools/gen_mm_logo.py: the Main Menu line logo, 20 x 20, 4 bits a pixel */\n"
    f"#define MM_LOGO_W {N}\n#define MM_LOGO_H {N}\n"
    f"static const uint8_t MM_LOGO[{len(data)}] = {{{body}}};\n")
# the boot screen's larger copy: 48 x 48, 4 bits of grey a pixel (15 = white), drawn 2 x 2
src = Image.new("L", (s, s), 255)
src.paste(im0, ((s - im0.width) // 2, (s - im0.height) // 2))
big = src.filter(ImageFilter.MinFilter(21)).resize((48, 48), Image.BOX)
gl = [min(15, max(0, round((255 - big.getpixel((x, y))) / 255 * 15 * 1.6))) for y in range(48) for x in range(48)]
gd = [gl[i] | gl[i + 1] << 4 for i in range(0, len(gl), 2)]
with open(root / "firmware/src/mm_logo.h", "a") as f:
    f.write("#define MM_LOGO_L 48\nstatic const uint8_t MM_LOGO_BIG[%d] = {%s};\n" % (len(gd), ",".join(str(b) for b in gd)))
for y in range(N):
    print("".join(" .#"[{0: 0, 2: 1, 3: 2}[pix[y * N + x]]] for x in range(N)))
